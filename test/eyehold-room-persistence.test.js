'use strict';
const assert = require('node:assert/strict');
const WorldModel = require('../frontend/app/worldmodel.js');
const state = WorldModel.create();
const first = state.rooms()[0].id;
assert.equal(state.setRoomTerritory(first, 'keep').ok, true);
assert.equal(state.roomById(first).eyeTerritory, 'keep');
const added = state.addRoom({kind:'lab',rect:{x1:20,y1:0,x2:26,y2:8}});
assert.equal(added.ok, true);
assert.equal(state.setRoomTerritory(added.id, 'forge').ok, true);
assert.equal(state.roomById(added.id).eyeTerritory, 'forge');
assert.equal(state.setRoomTerritory(added.id, '../invalid').ok, false);
const restored = WorldModel.deserialize(state.serialize());
assert.equal(restored.roomById(first).eyeTerritory, 'keep');
assert.equal(restored.roomById(added.id).eyeTerritory, 'forge');
restored.undo();
assert.equal(restored.roomById(added.id).eyeTerritory, undefined);
restored.redo();
assert.equal(restored.roomById(added.id).eyeTerritory, 'forge');
assert.equal(restored.setRoomTerritory('missing', 'forge').ok, false);
console.log('Eyehold canonical room persistence: OK');
