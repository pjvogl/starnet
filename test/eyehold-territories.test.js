'use strict';
const assert = require('node:assert/strict');
const T = require('../frontend/app/eyehold-territories.js');
const blank = T.normalize(null);
assert.equal(blank.schemaVersion, 1);
assert.equal(Object.keys(blank.rooms).length, 0);
let s = blank;
for (let i = 0; i < 30; i++) s = T.assign(s, 'room-' + i, { environmentId: i % 2 ? 'forge' : 'moonleaf', displayName: 'Hall ' + i });
assert.equal(Object.keys(s.rooms).length, 30, 'more than seven rooms must work');
assert.equal(s.rooms['room-1'].factionId, 'deepforge');
assert.equal(s.rooms['room-3'].environmentId, 'forge');
assert.equal(s.rooms['room-29'].displayName, 'Hall 29');
assert.equal(Object.keys(blank.rooms).length, 0, 'updates must not mutate prior state');
s = T.assign(s, 'custom-room', { environmentId: 'dragon-den' }, { 'dragon-den': { label: 'Dragon Den', factionId: 'dragon-keepers', assetSetId: 'dragon-v1' } });
assert.equal(s.rooms['custom-room'].assetSetId, 'dragon-v1');
assert.equal(T.resolve({ rooms: { mystery: { environmentId: 'missing-asset' } } }, 'mystery').environmentId, 'generic');
assert.equal(T.remove(s, 'room-1').rooms['room-1'], undefined);
assert.throws(() => T.assign(s, '../evil', {}), /Invalid room ID/);
assert.equal(T.normalize({ rooms: { '__proto__': { environmentId: 'forge' }, 'real': { environmentId: 'forge' } } }).rooms.real.environmentId, 'forge');
console.log('Eyehold territory registry: OK');
